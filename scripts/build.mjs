// FluentContext Pro — packaging. No dependencies.
//
//   node scripts/build.mjs [--target chromium|firefox|firefox-selfhosted|all] [--zip] [--repo owner/name]
//
// The repository root is itself a loadable Chromium extension. This script writes ready-to-load
// copies into dist/<target>/ and, with --zip, store-ready archives dist/fluentcontext-pro-<version>-<target>.zip
//   chromium            Chrome Web Store, Edge Add-ons, Opera, Brave (service worker background)
//   firefox             addons.mozilla.org listing (event-page background, gecko settings)
//   firefox-selfhosted  signed-by-AMO but distributed from GitHub releases (adds update_url)
import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { zip } from './zip.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const opt = (name, fallback) => { const i = args.indexOf(`--${name}`); return i >= 0 && args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : fallback; };
const flag = (name) => args.includes(`--${name}`);

const FILES = ['manifest.json', 'background.js', 'src', 'popup', 'icons'];
const manifest = JSON.parse(readFileSync(join(root, 'manifest.json'), 'utf8'));
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const version = manifest.version;
if (pkg.version !== version) {
  console.error(`✗ Version mismatch: package.json ${pkg.version} vs manifest.json ${version}. Use "npm run release".`);
  process.exit(1);
}

function detectRepo() {
  const explicit = opt('repo') || process.env.FC_REPO || process.env.GITHUB_REPOSITORY;
  if (explicit) return explicit;
  try {
    const url = execFileSync('git', ['remote', 'get-url', 'origin'], { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
    const m = /github\.com[:/]([\w.-]+\/[\w.-]+?)(\.git)?$/.exec(url);
    return m ? m[1] : '';
  } catch (e) {
    return '';
  }
}
const repo = detectRepo();
// Listed (AMO) and self-hosted builds are separate add-ons: AMO does not allow the same version number in both channels.
const geckoId = (pkg.fluentcontext && pkg.fluentcontext.geckoId) || 'fluentcontext-pro@local';
const geckoIdSelfHosted = (pkg.fluentcontext && pkg.fluentcontext.geckoIdSelfHosted) || 'fluentcontext-pro-selfhosted@local';

// Firefox has no extension service workers: list the modules the worker imports, then the worker.
const background = readFileSync(join(root, 'background.js'), 'utf8');
const imported = [...(/importScripts\(([^)]*)\)/.exec(background)?.[1] ?? '').matchAll(/'([^']+)'/g)].map((m) => m[1]);

function firefoxManifest(m, selfHosted) {
  const f = structuredClone(m);
  f.background = { scripts: [...imported, 'background.js'] };
  delete f.minimum_chrome_version;
  f.browser_specific_settings = {
    gecko: {
      id: selfHosted ? geckoIdSelfHosted : geckoId,
      strict_min_version: '128.0',
      data_collection_permissions: { required: ['none'] }
    },
    gecko_android: { strict_min_version: '128.0' }
  };
  if (selfHosted) {
    if (!repo) throw new Error('firefox-selfhosted needs a GitHub repository (git remote, --repo or GITHUB_REPOSITORY).');
    f.browser_specific_settings.gecko.update_url = `https://github.com/${repo}/releases/latest/download/updates.json`;
  }
  return f;
}

const TARGETS = {
  chromium: (m) => m,
  firefox: (m) => firefoxManifest(m, false),
  'firefox-selfhosted': (m) => firefoxManifest(m, true)
};

function listFiles(dir) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...listFiles(p));
    else out.push(p);
  }
  return out;
}

const want = opt('target', flag('zip') ? 'all' : 'chromium,firefox');
const targets = want === 'all' ? Object.keys(TARGETS).filter((t) => t !== 'firefox-selfhosted' || repo) : want.split(',');
mkdirSync(join(root, 'dist'), { recursive: true });

for (const target of targets) {
  const transform = TARGETS[target];
  if (!transform) { console.error(`✗ Unknown target ${target}`); process.exit(1); }
  const out = join(root, 'dist', target);
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  for (const f of FILES) if (f !== 'manifest.json') cpSync(join(root, f), join(out, f), { recursive: true });
  writeFileSync(join(out, 'manifest.json'), JSON.stringify(transform(manifest), null, 2) + '\n');
  writeFileSync(join(out, 'src', 'build-info.js'),
    `// Generated by scripts/build.mjs\n(function (g) {\n  const FC = (g.FC = g.FC || {});\n  FC.build = ${JSON.stringify({ repo, target, version })};\n})(self);\n`);
  let line = `✓ dist/${target}`;
  if (flag('zip')) {
    const entries = listFiles(out).map((p) => ({ name: relative(out, p).split(sep).join('/'), data: readFileSync(p) }));
    const file = join(root, 'dist', `fluentcontext-pro-${version}-${target}.zip`);
    writeFileSync(file, zip(entries));
    line += `  →  ${relative(root, file)} (${(statSync(file).size / 1024).toFixed(0)} KB, ${entries.length} files)`;
  }
  console.log(line);
}

// Firefox self-hosting manifest, served from the latest GitHub release.
if (repo && targets.includes('firefox-selfhosted')) {
  const updates = {
    addons: {
      [geckoIdSelfHosted]: {
        updates: [{ version, update_link: `https://github.com/${repo}/releases/download/v${version}/fluentcontext-pro-${version}-firefox-selfhosted.xpi` }]
      }
    }
  };
  writeFileSync(join(root, 'dist', 'updates.json'), JSON.stringify(updates, null, 2) + '\n');
  console.log('✓ dist/updates.json');
}
console.log(repo ? `  repo: ${repo}` : '  repo: (none — GitHub release checks disabled; add a git remote or pass --repo)');
if (!existsSync(join(root, 'dist'))) process.exit(1);
